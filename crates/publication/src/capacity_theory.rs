//! Analytical reference populations for the paper, NOT a generator-capacity estimator.
//!
//! All masses here are known by construction. No renders, model loading, fitting,
//! configuration inference or extrapolation of measured rooms occurs.
use crate::{graphics, io};
use anyhow::Result;
use serde_json::json;
use std::{fmt::Write, fs, path::Path};

fn absent(p: f64, n: u64) -> f64 {
    if n == 0 {
        1.
    } else {
        (n as f64 * (-p).ln_1p()).exp()
    }
}

fn occupied(p: f64, n: u64) -> f64 {
    if n == 0 {
        0.
    } else {
        -(n as f64 * (-p).ln_1p()).exp_m1()
    }
}

fn unique(masses: &[f64], n: u64) -> f64 {
    masses.iter().map(|&p| occupied(p, n)).sum()
}

fn collision(masses: &[f64]) -> f64 {
    masses.iter().map(|p| p * p).sum()
}

fn uniform_unique(support: f64, n: u64) -> f64 {
    support * occupied(1. / support, n)
}

fn zero_match_lower(pairs: u64, confidence: f64) -> f64 {
    1. / -((1. - confidence).ln() / pairs as f64).exp_m1()
}

/// Write tested analytical illustrations. These artifacts contain no empirical
/// claims about the renderer. Publication staging calls this automatically.
pub fn write(directory: &Path) -> Result<()> {
    fs::create_dir_all(directory)?;
    let draws = 10_000_000;
    let supports = [1_000_000., 10_000_000., 100_000_000.];
    let mut rows = Vec::new();
    let mut table = String::new();
    for support in supports {
        let unique = uniform_unique(support, draws);
        let novelty = absent(1. / support, draws);
        rows.push(json!({"support":support,"draws":draws,
            "expected_distinct":unique,"distinct_fraction":unique/draws as f64,
            "next_draw_novelty":novelty}));
        writeln!(
            table,
            "{:.0} million & {:.3} million & {:.2}\\% & {:.2}\\% \\\\",
            support / 1e6,
            unique / 1e6,
            100. * unique / draws as f64,
            100. * novelty,
        )?;
    }
    let tex = format!(
        r"% Generated by capacity_theory; known probability laws, not room measurements.
\begin{{figure}}[htbp]
\centering\includegraphics[width=\linewidth]{{generated/capacity_scaling.png}}
\caption{{Analytical occupancy examples, not measured Zeroverse capacity.
Left: distinct fraction for uniform populations with known support; dashed line
marks ten million draws. Right: two populations have the same collision diversity
$D_2=2$ but different occupancy curves and limiting support. A single effective
number does not determine long-run novelty.}}
\label{{fig:capacity-scaling}}
\end{{figure}}
\begin{{table}}[htbp]\centering\small
\begin{{tabular}}{{lrrr}}\toprule
Known uniform support & Expected distinct & Distinct/draws & Next-draw novelty\\
\midrule
{table}\bottomrule\end{{tabular}}
\caption{{Exact uniform-occupancy formulas at $n=10^7$, rounded for display.
No row estimates the support of this generator.}}\label{{tab:capacity-oracles}}
\end{{table}}
"
    );
    fs::write(directory.join("capacity_theory.tex"), tex)?;
    graphics::save(&figure(), &directory.join("capacity_scaling.svg"))?;
    io::write(
        &directory.join("capacity_oracles.json"),
        &json!({
            "schema_version":1,"kind":"analytical_reference",
            "generator_measurements":false,
            "source_sha256":bevy_zeroverse_capture::provenance::sha(include_bytes!("capacity_theory.rs")),
            "sampling":"IID with replacement; known, fixed, accepted-class probabilities",
            "uniform_examples":rows,
            "same_collision_different_support":[
                {"masses":[0.5,0.5],"d2":1./collision(&[0.5,0.5]),"unique_at_32":unique(&[0.5,0.5],32)},
                {"masses":[2./3.,1./6.,1./6.],"d2":1./collision(&[2./3.,1./6.,1./6.]),"unique_at_32":unique(&[2./3.,1./6.,1./6.],32)}
            ],
            "zero_matches":{"independent_disjoint_pairs":256,"confidence":0.95,
                "collision_diversity_lower_bound":zero_match_lower(256,0.95),
                "upper_bound":null}
        }),
    )?;
    Ok(())
}

fn line(svg: &mut String, x: f64, y: f64, x2: f64, y2: f64, color: &str) {
    write!(
        svg,
        "<path d='M{x:.2},{y:.2} L{x2:.2},{y2:.2}' fill='none' stroke='{color}' stroke-width='1'/>"
    )
    .unwrap();
}

fn figure() -> String {
    let mut svg = graphics::begin(1200, 470);
    graphics::text(&mut svg, 28., 32., 22, "What known population laws imply");
    graphics::text(
        &mut svg,
        28.,
        57.,
        14,
        "Analytical examples only; these curves do not estimate the procedural generator.",
    );
    let colors = ["#147d70", "#c56a33", "#626aca"];
    for panel in 0..2 {
        let left = 82. + 598. * panel as f64;
        let right = left + 460.;
        let top = 120.;
        let bottom = 370.;
        graphics::text(
            &mut svg,
            left,
            91.,
            17,
            if panel == 0 {
                "Uniform support: fraction of draws that are distinct"
            } else {
                "Equal D2 does not imply equal novelty"
            },
        );
        for tick in 0..=4 {
            let y = bottom - tick as f64 * (bottom - top) / 4.;
            line(&mut svg, left, y, right, y, "#dce3da");
            graphics::text(
                &mut svg,
                left - 48.,
                y + 5.,
                13,
                &if panel == 0 {
                    format!("{}%", tick * 25)
                } else {
                    format!("{:.2}", tick as f64 * 0.75)
                },
            );
        }
        line(&mut svg, left, bottom, right, bottom, "#60756a");
        if panel == 0 {
            for tick in 0..=4 {
                let x = left + tick as f64 * 115.;
                graphics::text(
                    &mut svg,
                    x - 18.,
                    bottom + 23.,
                    13,
                    ["10k", "100k", "1M", "10M", "100M"][tick],
                );
            }
            write!(
                svg,
                "<path d='M{0},120 L{0},370' stroke='#7b877f' stroke-dasharray='5 5'/>",
                left + 345.
            )
            .unwrap();
            for (i, support) in [1e6, 1e7, 1e8].into_iter().enumerate() {
                let mut path = String::new();
                for step in 0..=180 {
                    let t = step as f64 / 180.;
                    let n = 10_f64.powf(4. + 4. * t).round() as u64;
                    write!(
                        path,
                        "{} {:.2},{:.2} ",
                        if step == 0 { "M" } else { "L" },
                        left + 460. * t,
                        bottom - 250. * uniform_unique(support, n) / n as f64
                    )
                    .unwrap();
                }
                write!(
                    svg,
                    "<path d='{path}' fill='none' stroke='{}' stroke-width='3'/>",
                    colors[i]
                )
                .unwrap();
                line(
                    &mut svg,
                    left + i as f64 * 156.,
                    414.,
                    left + i as f64 * 156. + 20.,
                    414.,
                    colors[i],
                );
                graphics::text(
                    &mut svg,
                    left + i as f64 * 156. + 26.,
                    419.,
                    13,
                    ["S = 1 million", "S = 10 million", "S = 100 million"][i],
                );
            }
        } else {
            for n in [1, 8, 16, 24, 32] {
                graphics::text(
                    &mut svg,
                    left + 460. * (n - 1) as f64 / 31. - 7.,
                    bottom + 23.,
                    13,
                    &n.to_string(),
                );
            }
            for (i, masses) in [&[0.5, 0.5][..], &[2. / 3., 1. / 6., 1. / 6.][..]]
                .into_iter()
                .enumerate()
            {
                let mut path = String::new();
                for n in 1..=32 {
                    write!(
                        path,
                        "{} {:.2},{:.2} ",
                        if n == 1 { "M" } else { "L" },
                        left + 460. * (n - 1) as f64 / 31.,
                        bottom - 250. * unique(masses, n) / 3.
                    )
                    .unwrap();
                }
                write!(
                    svg,
                    "<path d='{path}' fill='none' stroke='{}' stroke-width='3'/>",
                    colors[i]
                )
                .unwrap();
                let y = 320. - i as f64 * 25.;
                line(&mut svg, left + 185., y, left + 207., y, colors[i]);
                graphics::text(
                    &mut svg,
                    left + 214.,
                    y + 5.,
                    13,
                    ["p = (1/2, 1/2)", "p = (2/3, 1/6, 1/6)"][i],
                );
            }
            graphics::text(
                &mut svg,
                left + 116.,
                419.,
                13,
                "Vertical axis: expected distinct classes",
            );
        }
        graphics::text(&mut svg, left + 175., 448., 14, "Independent draws");
    }
    svg.push_str("</g></svg>");
    svg
}

#[cfg(test)]
mod tests {
    use super::*;

    // Enumerate every sequence; independent of the closed-form occupancy code.
    fn enumerate(p: &[f64], n: usize, counts: &mut [usize], mass: f64) -> (f64, f64) {
        if n == 0 {
            let classes = counts.iter().filter(|&&c| c > 0).count();
            let pairs = counts
                .iter()
                .map(|&c| c * c.saturating_sub(1) / 2)
                .sum::<usize>();
            return (mass * classes as f64, mass * pairs as f64);
        }
        let mut sum = (0., 0.);
        for (j, &pj) in p.iter().enumerate() {
            counts[j] += 1;
            let r = enumerate(p, n - 1, counts, mass * pj);
            sum.0 += r.0;
            sum.1 += r.1;
            counts[j] -= 1;
        }
        sum
    }

    #[test]
    fn occupancy_and_collision_match_exhaustive_probability_tree() {
        for masses in [
            vec![1.],
            vec![0.5, 0.5],
            vec![0.6, 0.3, 0.1],
            vec![0., 0.5, 0.5],
        ] {
            for n in 0..=7 {
                let (u, pairs) = enumerate(&masses, n, &mut vec![0; masses.len()], 1.);
                assert!((u - unique(&masses, n as u64)).abs() < 1e-11);
                let expected = n * n.saturating_sub(1);
                assert!((pairs - expected as f64 * collision(&masses) / 2.).abs() < 1e-11);
            }
        }
    }

    #[test]
    fn novelty_and_bounds_hold_for_uniform_and_rare_tail_laws() {
        for p in [
            vec![1.],
            vec![0.5, 0.5],
            vec![0.999, 0.0009, 0.0001],
            vec![0.1; 10],
        ] {
            for n in 1..=1000 {
                let u = unique(&p, n);
                let lower = n as f64 / (1. + (n - 1) as f64 * collision(&p));
                assert!(u + 1e-10 >= lower && u <= p.len().min(n as usize) as f64 + 1e-10);
                let next: f64 = p.iter().map(|&pj| pj * absent(pj, n)).sum();
                assert!((unique(&p, n + 1) - u - next).abs() < 1e-12);
            }
        }
    }

    #[test]
    fn same_collision_diversity_does_not_determine_capacity() {
        let a = [0.5, 0.5];
        let b = [2. / 3., 1. / 6., 1. / 6.];
        assert!((collision(&a) - collision(&b)).abs() < 1e-15);
        assert!(unique(&b, 32) - unique(&a, 32) > 0.99);
    }

    #[test]
    fn stable_large_support_and_exact_zero_match_bound() {
        assert!((uniform_unique(1e20, 10_000_000) - 10_000_000.).abs() < 1e-5);
        assert_eq!(uniform_unique(1., 0), 0.);
        assert_eq!(uniform_unique(1., 100), 1.);
        let lower = zero_match_lower(256, 0.95);
        assert!(lower > 85. && lower < 87.);
        assert!(((1. - 1. / lower).powi(256) - 0.05).abs() < 1e-13);
    }

    #[test]
    fn artifacts_are_explicitly_analytical_and_reproducible() {
        let dir = tempfile::tempdir().unwrap();
        write(dir.path()).unwrap();
        let receipt: serde_json::Value =
            io::read(&dir.path().join("capacity_oracles.json")).unwrap();
        assert_eq!(receipt["generator_measurements"], false);
        assert!(
            receipt["uniform_examples"][2]["distinct_fraction"]
                .as_f64()
                .unwrap()
                > 0.95
        );
        let first = fs::read(dir.path().join("capacity_scaling.png")).unwrap();
        write(dir.path()).unwrap();
        assert_eq!(
            first,
            fs::read(dir.path().join("capacity_scaling.png")).unwrap()
        );
    }
}
