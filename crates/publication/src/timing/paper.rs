use super::*;
use std::fmt::Write as _;
fn tex(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            '_' => "\\_".into(),
            '%' => "\\%".into(),
            '&' => "\\&".into(),
            '#' => "\\#".into(),
            '$' => "\\$".into(),
            '{' => "\\{".into(),
            '}' => "\\}".into(),
            '\\' => "\\textbackslash{}".into(),
            '^' => "\\textasciicircum{}".into(),
            '~' => "\\textasciitilde{}".into(),
            _ => c.to_string(),
        })
        .collect()
}
fn n(v: &Value) -> f64 {
    v.as_f64().unwrap()
}
pub(super) fn serial_run(receipt: &Value) -> Result<&Value> {
    receipt["runs"]
        .as_array()
        .unwrap()
        .iter()
        .find(|r| {
            r["kind"] == "preparation"
                && r["summary"]["concurrent"] == 1
                && r["summary"]["gpu_material_recipes"] == true
        })
        .context("paper requires one sequential CPU preparation run using production GPU recipes")
}
pub(super) fn write(output: &Path, receipt: &Value) -> Result<()> {
    let cpu = serial_run(receipt)?;
    let env = &receipt["environment"];
    let summary = &cpu["summary"];
    let stats = &cpu["statistics"];
    let count = summary["rooms"].as_u64().unwrap();
    let seed = summary["seed"].as_u64().unwrap();
    let mut text = format!(
        r"% Generated by bevy_zeroverse_publication timing-study; do not edit.
\section{{Procedural pipeline and measured cost}}
\label{{sec:pipeline}}
Figure~\ref{{fig:pipeline-engine}} follows the production path from seeded programs to completed views. Immutable architecture, furnishing and person assemblies are constructed once. The same triangles supply transport and rendering. A shared pool with at most four dedicated preparation threads executes independent builders; scoped callers can also execute queued work. Large BVH subtrees use a separate shared pool of up to four threads. Ordered results and reserved mesh handles preserve seed identity. Material preparation overlaps geometry transport, group planning and mesh/tangent realization. Only referenced material variants are prepared. Supported material maps and their mip chains are baked once on the GPU; remaining programs use the CPU oracle. Native room lookahead overlaps preparation, bounded speculative uploads and static lighting with current capture, without promoting future scene entities early. The browser uses cooperative yields in place of native worker parallelism; yields keep the event loop responsive but do not provide CPU parallelism.

\subsection{{Protocol and accounting}}
Measurements use {}. {}. {}. These are shared-machine measurements, not isolated hardware limits or a training-throughput benchmark. The receipt binds source SHA256 \texttt{{{}}}, package versions, exact configuration, input hashes and every measured seed. No geometry, texture resolution, shadow quality or GI-ray budget is reduced for this study. Static AnnyBody people are sampled at density 0.25; ARDY inference is disabled.

The CPU-only study samples {count} consecutive rooms, seeds {seed}--{}, with {} separate warm-up rooms. It invokes the same preparation entry point as capture, including camera sampling, layout validation, geometry, material recipes, transport, reflections and lighting requests. It prepares GPU requests without executing them and cannot measure rendered throughput. Table~\ref{{tab:pipeline-stages}} partitions one future's monotonic wall lifetime into disjoint intervals. Values include scheduling/waiting within a stage, not CPU core time. Relative shares divide summed stage durations by summed preparation lifetimes; percentiles use nearest rank. Concurrent branch times and different rooms must not be summed into this partition.

\begin{{figure}}[htbp]\centering
\includegraphics[width=\linewidth]{{generated/pipeline_engine.png}}
\caption{{Production dependencies. The fork/join overlaps CPU material work with transport and mesh realization; GPU maps and lighting finish behind explicit readiness gates. Optional human inference is a separate gate. Consecutive-room lookahead spans these stages; the layout does not imply serial execution of whole rooms.}}
\label{{fig:pipeline-engine}}\end{{figure}}

\begin{{table}}[htbp]\centering\small
\begin{{tabular}}{{lrrrr}}\toprule
Preparation phase & Mean (ms) & Median (ms) & p95 (ms) & Share (\%)\\\midrule
",
        tex(env["hardware"].as_str().unwrap()),
        tex(env["build"].as_str().unwrap()),
        tex(env["contention"].as_str().unwrap()),
        &receipt["identity"]["source_sha256"].as_str().unwrap()[..16],
        seed + count - 1,
        summary["warmup_rooms"]
    );
    let total = n(&stats["total"]["sum"]);
    for (key, label) in STAGES {
        let s = &stats["wall"][key];
        writeln!(
            text,
            "{} & {:.2} & {:.2} & {:.2} & {:.2} \\\\",
            tex(label),
            n(&s["mean"]) * 1000.,
            n(&s["p50"]) * 1000.,
            n(&s["p95"]) * 1000.,
            100. * n(&s["sum"]) / total
        )?;
    }
    writeln!(text,"\\midrule Total & {:.2} & {:.2} & {:.2} & 100.00 \\\\\n\\bottomrule\\end{{tabular}}\n\\caption{{CPU preparation with production GPU material recipes, three square-aspect cameras and native Auto quality. The material/transport/mesh row counts the union once. Asset installation, actual GPU bakes, rendering and readback are downstream.}}\\label{{tab:pipeline-stages}}\\end{{table}}",n(&stats["total"]["mean"])*1000.,n(&stats["total"]["p50"])*1000.,n(&stats["total"]["p95"])*1000.)?;
    text.push_str("\n\\subsection{Completed capture and bounded concurrency}\nEach native capture run regenerates rooms and delivers three 512$\\times$512 views at one timestep in RGB, depth, position, normal, semantic and co-visibility modes. Full native shadows, SSAO, GPU materials and 256-ray/probe GI remain enabled. The default three-room lookahead is used. The streaming denominator includes validation, diagnostic JSONL writes and asset/sample destruction: preparation can advance during these operations. No image compression, dataset encoding or Burn tensor handoff is measured. Capture latency covers request to complete sample; it differs from streaming wall cost. GPU timestamp instrumentation is disabled in throughput runs.\n\n\\begin{table}[htbp]\\centering\\small\n\\begin{tabular}{lrrrr}\\toprule\nWorkload & Rooms & Wall rooms/s & Median (ms) & p95 (ms)\\\\\\midrule\n");
    let runs = receipt["runs"].as_array().unwrap();
    let mut capture_index = 0;
    for r in runs {
        let s = &r["summary"];
        let (label, rooms, rate, latency) = if r["kind"] == "preparation" {
            (
                format!("CPU preparation, {} in flight", s["concurrent"]),
                s["rooms"].as_u64().unwrap(),
                n(&s["prepared_rooms_per_second"]),
                r["statistics"]["total"].clone(),
            )
        } else {
            capture_index += 1;
            (
                format!("Completed capture, run {capture_index}"),
                s["scenes"].as_u64().unwrap() - s["warmup_scenes"].as_u64().unwrap(),
                n(&s["stream_scenes_per_second"]),
                super::stats(
                    r["records"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .map(|v| n(&v["elapsed_seconds"])),
                ),
            )
        };
        writeln!(
            text,
            "{label} & {rooms} & {rate:.3} & {:.1} & {:.1} \\\\",
            n(&latency["p50"]) * 1000.,
            n(&latency["p95"]) * 1000.
        )?;
    }
    text.push_str("\\bottomrule\\end{tabular}\n\\caption{Different denominators: CPU-only preparation emits immutable asset plans; completed capture emits all requested planes. Repeated capture runs expose shared-machine variability. Neither rate includes downstream training.}\\label{tab:pipeline-throughput}\\end{table}\n");
    for (i, r) in runs.iter().filter(|r| r["kind"] == "capture").enumerate() {
        let s = &r["summary"];
        writeln!(text,"Capture run {} excludes {} warm-up rooms; setup took {:.2} s and the first room took {:.2} s. The measured stream delivered {:.2} views/s; capture spans occupied {:.2}\\% of stream wall time. These spans overlap future-room work. Main-world installation records deferred ECS commands and asset insertion, not their later execution or upload.\n",i+1,s["warmup_scenes"],n(&s["startup_seconds"]),n(&r["cold_first_scene_seconds"]),n(&s["stream_views_per_second"]),100.*n(&s["measured_capture_seconds"])/n(&s["measured_stream_seconds"]))?;
    }
    let mut ordered: Vec<_> = STAGES.iter().collect();
    ordered.sort_by(|(a, _), (b, _)| {
        n(&stats["wall"][b]["sum"]).total_cmp(&n(&stats["wall"][a]["sum"]))
    });
    writeln!(text,"\\subsection{{Hot spots and next optimization targets}}\nThe largest measured preparation windows are {}, {} and {} (Figure~\\ref{{fig:pipeline-profile}}). They are observations of this workload, not universal cost ratios.",tex(ordered[0].1),tex(ordered[1].1),tex(ordered[2].1))?;
    let rows = cpu["records"].as_array().unwrap();
    let branch = |key: &str| super::stats(rows.iter().map(|r| n(&r["preparation_stages"][key])));
    writeln!(text,"Within the parallel asset window, mean material preparation is {:.1} ms, geometry transport construction is {:.1} ms, and mesh/tangent realization is {:.1} ms. Transport precedes meshes; that branch overlaps material work. Geometry builder service times are separately retained by architecture, object and person categories; their sums are not a CPU-utilization measurement.\n",n(&branch("materials_seconds")["mean"])*1000.,(n(&branch("transport_seconds")["mean"])-n(&stats["wall"]["transport_binding_seconds"]["mean"]))*1000.,n(&branch("meshes_seconds")["mean"])*1000.)?;
    text.push_str(r"Priority candidates are reducing triangle-staging and BVH-construction memory traffic, improving scheduling of the existing parallel transport subtrees, and GPU or batched reflection-environment synthesis. Camera visibility searches need independent rejection/attempt profiling before changing their budget: reducing the search budget can bias the camera distribution. Geometry assembly is separately measured, so finer-grained person/architecture scheduling should be pursued only when it is on the critical path. Any move of map or reflection work to the GPU must retain deterministic inputs, normal/roughness mip correctness, annotation alignment and measured completed capture throughput while training competes for the device. Pool expansion can increase contention; more workers are not automatically faster. Broad caching keyed only by material category would reduce procedural diversity and is not an acceptable optimization.

Render-preparation, GI/material readiness, settling and readback event-loop buckets are retained in the receipt. A bucket names the blocker observed before an update; it is not an exclusive CPU or GPU execution timer. Asynchronous GPU diagnostics can arrive late and contain nested intervals, so they are not summed into per-room GPU time. A GPU timeline profiler is still needed to attribute submission gaps, uploads and individual kernels. This study does not measure isolated GPU utilization, device-to-device tensor throughput, motion inference or browser latency. Wasm compilation checks preserve the path; browser timing requires a separate hardware-WebGPU run.

\begin{figure}[htbp]\centering\includegraphics[width=\linewidth]{generated/pipeline_profile.png}
\caption{Mean per-room CPU preparation wall time and its relative partition for the sequential CPU study. Colors separate the major phases; the parallel window includes scheduling and both branches, exactly once. This is not a utilization chart.}\label{fig:pipeline-profile}\end{figure}
\clearpage
");
    fs::write(output.join("pipeline_evaluation.tex"), text)?;
    Ok(())
}
